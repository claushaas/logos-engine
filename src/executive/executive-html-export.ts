function renderWarningBanner(): string {
	return `<div class="warning-banner">
  <strong>⚠️ DERIVED / NON-CANONICAL SNAPSHOT</strong><br>
  This document is a derived Executive Axis HTML export snapshot.
  It is <strong>not</strong> a canonical source of truth.
  The canonical source of truth is the normative documentation baseline and structured <code>.logos/</code> state.
  This export does <strong>not</strong> represent live task management or external system state.
</div>`;
}

function renderMetadataSection(meta: ExecutiveExportResultMetadata): string {
	let html = '<div class="metadata-block"><strong>Export Metadata</strong><ul>';
	html += `<li>Source Plan: <code>${escapeHtml(meta.sourcePlanId)}</code></li>`;
	html += `<li>Plan Fingerprint: ${escapeHtml(meta.sourcePlanFingerprint)}</li>`;
	html += `<li>Profile: ${escapeHtml(meta.profileId)}${meta.profileVersion ? ` v${escapeHtml(meta.profileVersion)}` : ''}</li>`;
	html += `<li>Generated At: ${escapeHtml(meta.generatedAt)}</li>`;
	html += `<li>Readiness: <code>${escapeHtml(meta.readinessStatus)}</code></li>`;
	html += `<li>Derived Snapshot: true</li>`;
	html += `<li>Non-Canonical: true</li>`;
	html += `<li>External API Execution: false</li>`;
	if (meta.sourceCanonicalDocumentIds.length > 0) {
		html += '<li>Source Documents: <ul>';
		for (const docId of meta.sourceCanonicalDocumentIds) {
			html += `<li><code>${escapeHtml(docId)}</code></li>`;
		}
		html += '</ul></li>';
	}
	html += '</ul></div>';
	return html;
}

function renderSummarySection(plan: ExecutivePlanJson): string {
	let html = '<section><h2>Summary</h2>';
	html += '<table>';
	html += `<tr><th>Project</th><td>${escapeHtml(plan.project.name)} (${escapeHtml(plan.project.id)})</td></tr>`;
	html += `<tr><th>Plan ID</th><td><code>${escapeHtml(plan.id)}</code></td></tr>`;
	html += `<tr><th>Version</th><td>${escapeHtml(plan.version)}</td></tr>`;
	html += `<tr><th>Generated At</th><td>${escapeHtml(plan.generatedAt)}</td></tr>`;
	html += `<tr><th>Readiness</th><td><code>${escapeHtml(plan.source.readinessStatus)}</code></td></tr>`;
	html += `<tr><th>Confidence</th><td>${escapeHtml(plan.confidence.overall)}</td></tr>`;
	if (plan.project.description) {
		html += `<tr><th>Description</th><td>${escapeHtml(plan.project.description)}</td></tr>`;
	}
	html += '</table></section>';
	return html;
}

function renderReadinessSection(plan: ExecutivePlanJson): string {
	let html = '<section><h2>Readiness Snapshot</h2>';
	html += `<p>Status: <code>${escapeHtml(plan.source.readinessStatus)}</code></p>`;
	if (plan.source.warnings.length > 0) {
		html += '<p><strong>Warnings:</strong></p><ul>';
		for (const w of plan.source.warnings) {
			html += `<li>⚠️ ${escapeHtml(w)}</li>`;
		}
		html += '</ul>';
	}
	if (plan.metadata && typeof plan.metadata === 'object') {
		const meta = plan.metadata as Record<string, unknown>;
		if (meta.readinessSummary) {
			const rs = meta.readinessSummary as Record<string, unknown>;
			html += '<table><tr><th>Metric</th><th>Value</th></tr>';
			const metrics: Array<[string, unknown]> = [
				['Total Documents', rs.totalDocuments],
				['Satisfied', rs.satisfiedDocuments],
				['Warning', rs.warningDocuments],
				['Blocked', rs.blockedDocuments],
				['Blockers', rs.blockerCount],
			];
			for (const [k, v] of metrics) {
				html += `<tr><td>${escapeHtml(k)}</td><td>${v ?? 'N/A'}</td></tr>`;
			}
			html += '</table>';
		}
	}
	html += '</section>';
	return html;
}

function renderRoadmapsSection(plan: ExecutivePlanJson): string {
	if (!plan.execution.roadmaps || plan.execution.roadmaps.length === 0) {
		return '<section><h2>Roadmap</h2><p>No roadmaps defined.</p></section>';
	}
	let html = '<section><h2>Roadmap</h2>';
	for (const r of plan.execution.roadmaps) {
		html += `<h3>${escapeHtml(r.title)}</h3>`;
		html += `<p>${escapeHtml(r.description)}</p>`;
		html += '<table>';
		html += `<tr><th>Status</th><td>${statusBadge(r.status)}</td></tr>`;
		html += `<tr><th>Horizon</th><td>${escapeHtml(r.horizon)}</td></tr>`;
		html += `<tr><th>Milestones</th><td>${r.milestoneIds.map((m) => `<code>${escapeHtml(m)}</code>`).join(', ')}</td></tr>`;
		html += '</table>';
	}
	html += '</section>';
	return html;
}

