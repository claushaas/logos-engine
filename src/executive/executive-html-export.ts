// ---------------------------------------------------------------------------
// HTML document structure
// ---------------------------------------------------------------------------

function htmlStart(title: string): string {
	const escapedTitle = escapeHtml(title);
	return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${escapedTitle}</title>
<style>
${CSS}
</style>
</head>
<body>
`;
}

function htmlEnd(): string {
	return `
<footer>
  <p>Generated by LOGOS Engine — Executive Axis HTML Export</p>
  <p>This is a derived, non-canonical snapshot. No external systems were contacted.</p>
</footer>
</body>
</html>
`;
}

// ---------------------------------------------------------------------------
// Status badge
// ---------------------------------------------------------------------------

function statusBadge(status: string): string {
	let cls = 'status-planned';
	let label = status;
	switch (status) {
		case 'blocked':
			cls = 'status-blocked';
			label = '🚫 BLOCKED';
			break;
		case 'reviewing':
		case 'requires_review':
			cls = 'status-review';
			label = '👁️ REQUIRES REVIEW';
			break;
		case 'deferred':
		case 'draft':
			cls = 'status-deferred';
			label = status === 'deferred' ? '⏸️ DEFERRED' : 'Draft';
			break;
		case 'done':
			cls = 'status-done';
			label = '✅ Done';
			break;
		case 'ready':
		case 'planned':
			cls = 'status-planned';
			label = '📋 Planned';
			break;
	}
	return `<span class="status-badge ${cls}">${label}</span>`;
}

