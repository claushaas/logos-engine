function runSecurityChecks(content: string): ExecutiveExportSecuritySummary {
	const checks: ExecutiveExportSecurityCheck[] = [
		{
			checkId: 'no_scripts',
			name: 'No script tags',
			passed: !/<script/i.test(content),
		},
		{
			checkId: 'no_inline_handlers',
			name: 'No inline event handlers',
			passed: !/\son\w+\s*=/i.test(content),
		},
		{
			checkId: 'no_external_stylesheets',
			name: 'No external stylesheets',
			passed: !/<link\s+rel=["']stylesheet/i.test(content),
		},
		{
			checkId: 'no_remote_fonts',
			name: 'No remote fonts',
			passed: !(
				/@import\s+url\(['"]https?:\/\//i.test(content) ||
				/url\(['"]https?:\/\//i.test(content)
			),
		},
		{
			checkId: 'no_iframes',
			name: 'No iframe tags',
			passed: !/<iframe/i.test(content),
		},
		{
			checkId: 'no_forms',
			name: 'No form tags',
			passed: !/<form/i.test(content),
		},
		{
			checkId: 'no_javascript_protocol',
			name: 'No javascript: protocol',
			passed: !/javascript:/i.test(content) && !/vbscript:/i.test(content),
		},
		{
			checkId: 'no_raw_tokens',
			name: 'No raw provider tokens',
			passed: !/sk-[a-zA-Z0-9]{20,}/.test(content),
		},
		{
			checkId: 'no_auth_headers',
			name: 'No authorization headers',
			passed: !/bearer [a-zA-Z0-9_.-]{20,}/i.test(content),
		},
		{
			checkId: 'no_canonical_claim',
			name: 'No canonical authority claim',
			passed: !content.includes('canonical source of truth: this document'),
		},
	];

	const allPassed = checks.every((c) => c.passed);
	return { checks, passed: allPassed };
}

// ---------------------------------------------------------------------------
// Render
// ---------------------------------------------------------------------------

function render(
	input: ExecutiveExportInput,
	options: ExecutiveExportOptions = {},
): ExecutiveExportResult {
	const diagnostics: ExecutiveExportDiagnostic[] = [];
	const plan = input.plan;
	const mapping = input.mapping;
	const timestamp = options.injectTimestamp ?? input.clock();
	const targetId = options.injectTargetId ?? `${mapping.mappingId}-html-export`;

	const sourceCanonicalDocIds: string[] = Array.isArray(
		plan.source.normativeDocuments,
	)
		? (plan.source.normativeDocuments as string[])
		: [];

	const meta: ExecutiveExportResultMetadata = {
		derivedSnapshot: true,
		externalApiExecution: false,
		generatedAt: timestamp,
		nonCanonical: true,
		profileId: input.profileId,
		profileVersion: input.profileVersion,
		readinessStatus: input.readinessStatus,
		schemaValidationStatus: 'passed',
		sourceCanonicalDocumentIds: sourceCanonicalDocIds,
		sourceCanonicalPaths: sourceCanonicalDocIds.map(
			(d) => `${input.documentationRoot}${d}.md`,
		),
		sourcePlanFingerprint: input.planFingerprint,
		sourcePlanId: input.planId,
	};

	const body = [
		renderWarningBanner(),
		renderMetadataSection(meta),
		renderSummarySection(plan),
		renderReadinessSection(plan),
		renderRoadmapsSection(plan),
		renderMilestonesSection(plan),
		renderInitiativesSection(plan),
		renderWorkItemsSection(plan),
		renderBlockersSection(plan),
		renderRisksSection(plan),
		renderDecisionsSection(plan),
		renderAcceptanceCriteriaSection(plan),
		renderTraceabilitySection(meta),
		renderExportMetadataSection(plan),
	].join('\n');

	const content = `${htmlStart(plan.project.name)}\n${body}\n${htmlEnd()}`;
	const checksum = createHash('sha256')
		.update(content)
		.digest('hex')
		.slice(0, 16);

	const outputPath =
		mapping.outputPath ??
		'outcomes/executive/exports/html/executive-overview.html';
	const securitySummary = runSecurityChecks(content);

	return {
		adapterKind: 'html',
		changedPaths: [],
		diagnostics,
		metadata: meta,
		readOnly: true,
		renderedFiles: [
			{
				checksum,
				content,
				format: 'html',
				relativePath: outputPath,
				targetId,
			},
		],
		securitySummary,
		supportStatus: 'supported_file_export',
		targetId,
		title: `Executive HTML Export: ${plan.project.name}`,
	};
}
