function renderWorkItemsSection(plan: ExecutivePlanJson): string {
	if (!plan.execution.items || plan.execution.items.length === 0) {
		return '<section><h2>Work Items</h2><p>No work items defined.</p></section>';
	}
	let html = '<section><h2>Work Items</h2>';
	for (const item of plan.execution.items) {
		html += `<h3>${escapeHtml(item.title)}</h3>`;
		html += `<p>${statusBadge(item.status)} <code>${escapeHtml(item.id)}</code> | Type: <code>${escapeHtml(item.type)}</code> | Priority: <code>${escapeHtml(item.priority)}</code></p>`;
		html += `<p>${escapeHtml(item.description)}</p>`;
		if (item.acceptanceCriteria.length > 0) {
			html += '<p><strong>Acceptance Criteria:</strong></p><ul>';
			for (const c of item.acceptanceCriteria) {
				html += `<li>${escapeHtml(c)}</li>`;
			}
			html += '</ul>';
		}
		if (item.sourceNormativeDocuments.length > 0) {
			html += '<p><strong>Source Documents:</strong></p><ul>';
			for (const d of item.sourceNormativeDocuments) {
				html += `<li><code>${escapeHtml(d)}</code></li>`;
			}
			html += '</ul>';
		}
		if (item.dependsOn.length > 0) {
			html += '<p><strong>Dependencies:</strong></p><ul>';
			for (const d of item.dependsOn) {
				html += `<li><code>${escapeHtml(d)}</code></li>`;
			}
			html += '</ul>';
		}
	}
	html += '</section>';
	return html;
}

function renderBlockersSection(plan: ExecutivePlanJson): string {
	const blockers =
		plan.execution.items?.filter((i) => i.status === 'blocked') ?? [];
	const rcItems =
		plan.execution.items?.filter((i) => i.status === 'reviewing') ?? [];

	if (blockers.length === 0 && rcItems.length === 0) {
		return '<section><h2>Blockers &amp; Requires Review</h2><p>No blocked or review-required items.</p></section>';
	}
	let html = '<section><h2>Blockers &amp; Requires Review</h2>';

	if (blockers.length > 0) {
		html += '<h3>🚫 Blocked</h3><ul>';
		for (const b of blockers) {
			html += `<li><strong>${escapeHtml(b.title)}</strong> (<code>${escapeHtml(b.id)}</code>) — ${escapeHtml(b.priority)}</li>`;
		}
		html += '</ul>';
	}
	if (rcItems.length > 0) {
		html += '<h3>👁️ Requires Review</h3><ul>';
		for (const b of rcItems) {
			html += `<li><strong>${escapeHtml(b.title)}</strong> (<code>${escapeHtml(b.id)}</code>)</li>`;
		}
		html += '</ul>';
	}
	html += '</section>';
	return html;
}

